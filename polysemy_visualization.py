# my reimplementation of the now-defunct context atlas:
# given a data frame with sentences with a common target word,
# compute contextualized embeddings and visualize them in 2d,
# with sentence snippets visible as you hover over the points,
# and with indicative words of different regions of the space
# superimposed in big letters.
#
# input:
# df: data frame with columns "sent", "tgt", for computing sentence snippets
# what: column containing the target word
# embeddings: if given, don't recompute
# layerlabel: "last" or "last4", layers to use if embeddings are computed from scratch
# numclusters: number of clusters to use when grouping points into clusters for computing indicative words
# clustercolors: color in the clusters? if not, all points are silver
# modeltype: language model to use to compute embeddings
#
# returns: cluster label for each data point,
#          most indicative word for each cluster (dict clusterlabel -> word)
def contextatlas(df, what = "tgt", embeddings = None, layerlabel = "last4", numclusters = 5, showwords = True,
                     clustercolors = False, modeltype = 'bert-base-uncased'):
    ### obtain embeddings
    if embeddings is None:
        compute_embeddings_for(df, what = what, layerlabel = layerlabel, batchsize = 100, modeltype = modeltype)

    ### downproject for visualization
    twodim = reduce_dim(embeddings, dimred_method = "TSNE")

    ### obtain text for characterizing groups of points:
    # 1. cluster datapoints
    clusterlabels, clustercentroids, clustercentralpoints = compute_clusters(embeddings, numclusters = numclusters)

    # 2. compute tf/idf words for each cluster
    # for each cluster, select a smaller number of words centered on the target
    sentence_snippets = make_sentence_snippets(df, windowsize = 10)
    clusterwords = defaultdict(list)
    for ix, s in enumerate(sentence_snippets):
        clusterindex = clusterlabels[ix]
        words = s.split()
        clusterwords[ clusterindex ] += words

    # don't count the target word, or one of a small list of stopwords, in tf-idf
    excludewords = list(set([w.lower() for w in df.tgt]))
    excludewords += ["i", "you", "he", "she", "it", "they", "we", "us", "is", "was", "be", "do", "does", 
                      "did", "ca", "can"]

    # compute tf-idf
    cluster_tfidf = compute_tfidf([clusterwords[i] for i in range(numclusters)], excludewords= excludewords)
    # for each cluster, find the word with maximum tf-idf
    cluster_maxword = { }
    for clusterindex in range(numclusters):
        cluster_maxword[clusterindex] = sorted(cluster_tfidf[clusterindex].items(), \
                                               key = lambda p:p[1], reverse = True)[0][0]

    # 3. determine coordinates for printing central words:
    # at the central item
    if showwords: 
        clustertexts = [ ]
        for clusterindex, word in cluster_maxword.items():
            xcoord = twodim[ clustercentralpoints[clusterindex],0]
            ycoord = twodim[ clustercentralpoints[clusterindex],1]
            clustertexts.append( ( word, xcoord, ycoord) )
    else:
        clustertexts = None

    ### and visualize
    if clustercolors:
        pointcolors = clusterlabels
    else:
        pointcolors = None
    draw_points(df, twodim, pointcolors = pointcolors, bigtexts = clustertexts)

    return clusterlabels, cluster_maxword
